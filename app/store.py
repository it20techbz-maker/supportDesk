"""Storage for messages, tickets, replies, emails and the audit log.

SQLite for running on one machine. Postgres (Supabase) when DATABASE_URL is set.
Both offer the same four methods, and SQL is written once with "?" placeholders.
"""
import sqlite3
import threading

_TABLES = {
    "inbound": "ts text, phone text, text text, masked text, type text, ticket_id integer",
    "tickets": "ext_id text, ts text, phone text, company text, title text, body text, priority text, "
    "environment text, settle_by text, status text, root_cause text",
    "outbox": "ts text, phone text, kind text, body text, status text, ticket_id integer, approved_by text, "
    "sent_ts text, via text",
    "emails": "ts text, recipient text, subject text, body text",
    "pending": "ts text, inbound_id integer, kind text, attachments text, attempts integer default 0",
    "audit": "ts text, event text, detail text",
    "settings": "key text, value text",
}


class _Base:
    def one(self, sql, args=()):
        rows = self.all(sql, args)
        return rows[0] if rows else None

    def audit(self, ts, event, detail=""):
        self.run("insert into audit (ts, event, detail) values (?, ?, ?)", (ts, event, detail))

    def get_setting(self, key, default=""):
        row = self.one("select value from settings where key = ?", (key,))
        return row["value"] if row else default

    def set_setting(self, key, value):
        self.run("delete from settings where key = ?", (key,))
        self.run("insert into settings (key, value) values (?, ?)", (key, value))


class Store(_Base):
    """SQLite."""

    def __init__(self, path):
        self._db = sqlite3.connect(path, check_same_thread=False)
        self._db.row_factory = sqlite3.Row
        self._lock = threading.Lock()
        with self._lock:
            for name, columns in _TABLES.items():
                self._db.execute("create table if not exists %s (id integer primary key, %s)" % (name, columns))
            self._db.commit()

    def run(self, sql, args=()):
        """Execute a change. For an insert, returns the new row's id."""
        with self._lock:
            cur = self._db.execute(sql, args)
            self._db.commit()
            return cur.lastrowid

    def all(self, sql, args=()):
        with self._lock:
            return [dict(r) for r in self._db.execute(sql, args).fetchall()]


class PostgresStore(_Base):
    """Postgres, for example a Supabase project.

    Works with Supabase's transaction pooler (port 6543), which is the right
    connection string for serverless hosting such as Vercel.
    """

    def __init__(self, url):
        import psycopg
        from psycopg.rows import dict_row

        self._psycopg = psycopg
        self._row_factory = dict_row
        self._url = url
        self._conn = None
        self._lock = threading.Lock()
        with self._lock:
            for name, columns in _TABLES.items():
                self._execute(
                    "create table if not exists %s (id bigint generated by default as identity primary key, %s)"
                    % (name, columns)
                )
                # Supabase publishes tables in the public schema through its own web API.
                # Row level security with no policies keeps these tables out of it.
                self._execute("alter table %s enable row level security" % name)

    def _execute(self, sql, args=None):
        # One retry, because a serverless instance can wake up holding a dead connection.
        for attempt in (1, 2):
            try:
                if self._conn is None or self._conn.closed or self._conn.broken:
                    self._conn = self._psycopg.connect(
                        self._url, autocommit=True, row_factory=self._row_factory, prepare_threshold=None
                    )
                return self._conn.execute(sql, args)
            except self._psycopg.OperationalError:
                self._conn = None
                if attempt == 2:
                    raise

    def run(self, sql, args=()):
        """Execute a change. For an insert, returns the new row's id."""
        insert = sql.lstrip().lower().startswith("insert")
        sql = sql.replace("?", "%s") + (" returning id" if insert else "")
        with self._lock:
            cur = self._execute(sql, tuple(args))
            return cur.fetchone()["id"] if insert else None

    def all(self, sql, args=()):
        with self._lock:
            return [dict(r) for r in self._execute(sql.replace("?", "%s"), tuple(args)).fetchall()]
